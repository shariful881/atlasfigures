// build-country-list (task 158): the master list of every country or area in UN WPP 2024 (237), with the slug
// that fixes its URLs (/country/<slug>/…), its common and UN names, regions and which pages exist.
// Writes src/data/country-list.json, which IS committed (slugs are URLs: once a slug exists it never changes —
// this script keeps every slug already in the file and only adds new ones).
//   node scripts/build-country-list.mjs          (after `npm run data`)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';

const OUT = 'src/data/country-list.json';
const wpp = JSON.parse(readFileSync('src/data/wpp/index.json', 'utf8')).countries;
const names = JSON.parse(readFileSync('src/data/common-names.json', 'utf8')).names;
const wdiDir = 'src/data/wdi/countries';
const wdi = existsSync(wdiDir) ? Object.fromEntries(readdirSync(wdiDir).map((f) => { const d = JSON.parse(readFileSync(`${wdiDir}/${f}`, 'utf8')); return [d.iso3, d]; })) : {};
const old = existsSync(OUT) ? Object.fromEntries(JSON.parse(readFileSync(OUT, 'utf8')).countries.map((c) => [c.iso3, c])) : {};

// editorial JSONs of existing pages: their slug and names win (they are already live URLs)
const ed = {};
for (const [dir, topic] of [['src/data/countries', 'population'], ['src/data/economy', 'economy']]) {
  for (const f of readdirSync(dir)) {
    const j = JSON.parse(readFileSync(`${dir}/${f}`, 'utf8'));
    const e = (ed[j.iso3] ??= { pages: [] });
    for (const k of ['slug', 'name', 'demonym', 'capital']) if (j[k] && !e[k]) e[k] = j[k];
    e.pages.push(topic);
  }
}
// hubs and topic pages written from task 160 on (src/data/country-pages/<slug>.json: pages.hub, pages.health …)
if (existsSync('src/data/country-pages')) for (const f of readdirSync('src/data/country-pages')) {
  const j = JSON.parse(readFileSync(`src/data/country-pages/${f}`, 'utf8'));
  const e = (ed[j.iso3] ??= { pages: [] });
  for (const k of ['slug', 'name', 'demonym', 'capital']) if (j[k] && !e[k]) e[k] = j[k];
  for (const t of Object.keys(j.pages)) if (!e.pages.includes(t)) e.pages.push(t);
}
const slugify = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/['’.]/g, '').replace(/\(.*?\)/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const SLUG = { HKG: 'hong-kong', MAC: 'macao', VAT: 'vatican-city', MAF: 'saint-martin', SXM: 'sint-maarten', FSM: 'micronesia', VIR: 'us-virgin-islands', FLK: 'falkland-islands', TWN: 'taiwan', PSE: 'palestine', BES: 'caribbean-netherlands' };

const list = wpp.map((c) => {
  const e = ed[c.iso3] ?? { pages: [] };
  const name = e.name ?? names[c.iso3] ?? c.unName;
  const slug = old[c.iso3]?.slug ?? e.slug ?? SLUG[c.iso3] ?? slugify(name);
  const w = wdi[c.iso3];
  return {
    iso3: c.iso3, iso2: c.iso2, slug, name, unName: c.unName,
    unRegion: c.region, unSubregion: c.subregion,
    wbRegion: w?.region ?? null, incomeGroup: w?.incomeGroup ?? null,
    capital: e.capital ?? null, demonym: e.demonym ?? null,
    pages: e.pages.sort(),
  };
}).sort((a, b) => a.name.localeCompare(b.name, 'en'));

const dup = list.map((c) => c.slug).filter((s, i, a) => a.indexOf(s) !== i);
if (dup.length) throw new Error(`duplicate slugs: ${dup.join(', ')}`);
for (const [iso3, c] of Object.entries(old)) {
  const now = list.find((x) => x.iso3 === iso3);
  if (!now) throw new Error(`${iso3} (${c.slug}) disappeared from UN WPP — decide by hand, never drop a live URL silently`);
}
writeFileSync(OUT, JSON.stringify({
  _about: 'Every country or area in UN WPP 2024 (task 158). slug = URL (/country/<slug>/…) and never changes once set. Generated by scripts/build-country-list.mjs; names from page JSONs, src/data/common-names.json or the UN. capital/demonym only where a page has them (more from task 156).',
  count: list.length, countries: list,
}, null, 1) + '\n');
console.log(`✓ ${OUT}: ${list.length} countries or areas (${list.filter((c) => c.pages.length).length} with pages, ${list.filter((c) => c.wbRegion).length} in World Bank data)`);
